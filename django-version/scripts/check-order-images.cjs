const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const sandbox = {window:{},File,FormData,Date};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','static','order-images.js'),'utf8'),sandbox);
const images = sandbox.window.MesaOrderImages;
const png = new File(['test-image'], 'test.png', {type:'image/png'});
const form = images.body({version:3,actions:'Trabajo listo',completion_image:png});
assert(form instanceof FormData);
assert.equal(JSON.parse(form.get('data')).version,3);
assert.equal(JSON.parse(form.get('data')).actions,'Trabajo listo');
assert.equal(form.get('completion_image').name,'test.png');
assert(!('completion_image' in JSON.parse(form.get('data'))));
assert.deepEqual(JSON.parse(images.body({version:4,completion_image:new File([],'')})),{version:4});
assert.throws(()=>images.body({report_image:new File([],'empty.png',{type:'image/png'})}),/contenido/);
assert.throws(()=>images.body({report_image:new File(['<svg/>'],'bad.svg',{type:'image/svg+xml'})}),/JPG/);
assert.throws(()=>images.body({report_image:new File([new Uint8Array(8*1024*1024+1)],'big.png',{type:'image/png'})}),/8 MB/);
const gallery = images.gallery([{id:1,kind:'report',url:'/api/orders/1/images/1',width:1600,height:1200,created_by:'<script>unsafe</script>',created_at:'2026-10-20T12:00:00Z'}]);
assert(gallery.includes('&lt;script&gt;unsafe&lt;/script&gt;'));
assert(!gallery.includes('<script>'));
assert(gallery.includes('Falla reportada'));
assert(images.gallery([{kind:'completion',url:'/api/orders/1/images/2',width:1600,height:1200,created_at:'2026-10-20T12:00:00Z'}]).includes('Trabajo terminado'));
assert(images.field('report_image','Foto').includes('type="file"'));
assert(images.field('report_image','Foto').includes('aria-describedby='));
console.log('Adjuntos: envío multipart, captura sin imagen, límites, formatos y escape de metadatos OK.');
